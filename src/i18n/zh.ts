/** The simplified characters in the book names that are written differently in traditional Chinese */
const TRADITIONAL: Record<string, string> = {
  记: '記', 纪: '紀', 约: '約', 书: '書', 亚: '亞', 历: '歷', 诗: '詩', 传: '傳', 赛: '賽', 结: '結', 弥: '彌',
  鸿: '鴻', 该: '該', 玛: '瑪', 马: '馬', 罗: '羅', 后: '後', 来: '來', 犹: '猶', 启: '啟', 录: '錄', 门: '門',
  数: '數', 师: '師', 创: '創', 贰: '貳',
};
const traditional = (s: string) => [...s].map((c) => TRADITIONAL[c] ?? c).join('');

export const books: BookNames = simplified.map(([name, abbr]) => [
  name,
  [...new Set([...abbr, traditional(name), ...abbr.map(traditional)])].filter((a) => a !== name),
]);

