// After `astro build`: moves every non-English translation out of dist/ into dist-langs/{lang}/site/, with a
// generated wrangler.jsonc for a files-only Worker per language (booksor-es, booksor-pt…). Each Worker gets a
// route per translation, so booksor.com/rv1909/john/3 is served by booksor-es while everything else stays on
// the main Worker. This keeps every Worker under Cloudflare's 20,000-file limit. See docs/plans/more-languages.md.
//
// It moves files, so it needs a fresh build: `pnpm build && pnpm run split`.
// Run with: node scripts/split-dist.ts
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const MAX_FILES = 19_000; // Cloudflare allows 20,000 files per Worker; keep a margin
export const ZONE = 'booksor.com';

type Translation = { id: string; language: string };
type MainConfig = {
  compatibility_date: string;
  assets: { html_handling?: string; not_found_handling?: string };
};
export type LangWorker = { lang: string; name: string; dir: string; ids: string[]; files: number };

export function countFiles(dir: string): number {
  return readdirSync(dir, { withFileTypes: true }).reduce(
    (n, e) => n + (e.isDirectory() ? countFiles(join(dir, e.name)) : 1),
    0,
  );
}

/** wrangler.jsonc, minus its whole-line comments */
export function readMainConfig(path: string): MainConfig {
  return JSON.parse(readFileSync(path, 'utf8').replace(/^\s*\/\/.*$/gm, ''));
}

/** A route is a prefix match (`booksor.com/rv1909*`), so no translation id may start another top-level path. */
export function prefixClashes(ids: string[], topLevel: string[]): string[] {
  const names = new Set([...topLevel.map((n) => n.replace(/\.html$/, '')), ...ids]);
  return ids.flatMap((id) => [...names].filter((n) => n !== id && n.startsWith(id)).map((n) => `/${id}* would also catch /${n}`));
}

export function workerConfig(lang: string, ids: string[], main: MainConfig) {
  return {
    name: `booksor-${lang}`,
    compatibility_date: main.compatibility_date,
    workers_dev: false,
    preview_urls: false,
    assets: {
      directory: './site',
      html_handling: main.assets.html_handling,
      not_found_handling: main.assets.not_found_handling,
    },
    routes: ids.map((id) => ({ pattern: `${ZONE}/${id}*`, zone_name: ZONE })),
  };
}

export function splitDist(opts: {
  dist: string;
  out: string;
  translations: Translation[];
  main: MainConfig;
  maxFiles?: number;
}): { mainFiles: number; workers: LangWorker[] } {
  const { dist, out, translations, main, maxFiles = MAX_FILES } = opts;
  const moving = translations.filter((t) => t.language !== 'en');

  const missing = moving.filter((t) => !existsSync(join(dist, t.id)) || !existsSync(join(dist, `${t.id}.html`)));
  if (missing.length) {
    throw new Error(
      `dist/ has no ${missing.map((t) => t.id).join(', ')}. The split moves files out of dist/, so build again first.`,
    );
  }
  const clashes = prefixClashes(moving.map((t) => t.id), readdirSync(dist));
  if (clashes.length) throw new Error(`Route clash: ${clashes.join('; ')}`);

  rmSync(out, { recursive: true, force: true });
  const byLang = Map.groupBy(moving, (t) => t.language);
  const workers: LangWorker[] = [];
  for (const [lang, list] of byLang) {
    const dir = join(out, lang);
    const site = join(dir, 'site');
    mkdirSync(site, { recursive: true });
    for (const { id } of list) {
      renameSync(join(dist, `${id}.html`), join(site, `${id}.html`));
      renameSync(join(dist, id), join(site, id));
    }
    copyFileSync(join(dist, '404.html'), join(site, '404.html'));
    const ids = list.map((t) => t.id);
    const config = workerConfig(lang, ids, main);
    writeFileSync(
      join(dir, 'wrangler.jsonc'),
      `// Generated by scripts/split-dist.ts: don't edit. Files-only Worker for the ${lang} translations.\n` +
        JSON.stringify(config, null, 2) +
        '\n',
    );
    workers.push({ lang, name: config.name, dir, ids, files: countFiles(site) });
  }

  const mainFiles = countFiles(dist);
  const over = [
    ...(mainFiles > maxFiles ? [`main Worker (dist/): ${mainFiles}`] : []),
    ...workers.filter((w) => w.files > maxFiles).map((w) => `${w.name}: ${w.files}`),
  ];
  if (over.length) {
    throw new Error(
      `Over ${maxFiles.toLocaleString()} files: ${over.join(', ')}. ` +
        'Split that language over a second Worker, or see docs/plans/more-languages.md.',
    );
  }
  return { mainFiles, workers };
}

if (import.meta.main) {
  const root = join(import.meta.dirname, '..');
  const translations: Translation[] = JSON.parse(readFileSync(join(root, 'data', 'translations.json'), 'utf8'));
  const { mainFiles, workers } = splitDist({
    dist: join(root, 'dist'),
    out: join(root, 'dist-langs'),
    translations,
    main: readMainConfig(join(root, 'wrangler.jsonc')),
  });
  console.log(`✓ booksor (dist/): ${mainFiles.toLocaleString()} files`);
  for (const w of workers) {
    console.log(`✓ ${w.name} (dist-langs/${w.lang}/): ${w.files.toLocaleString()} files, ${w.ids.map((id) => `/${id}`).join(' ')}`);
  }
}
