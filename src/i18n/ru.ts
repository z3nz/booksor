const rules = new Intl.PluralRules('ru');
/** "1 глава", "3 главы", "5 глав" */
const plural = (n: number, one: string, few: string, many: string) =>
  `${n.toLocaleString('ru')} ${({ one, few } as Record<string, string>)[rules.select(n)] ?? many}`;

