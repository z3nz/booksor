const rules = new Intl.PluralRules('ar');
/** Arabic counts: 1 and 2 have their own forms, 3–10 take the plural, 11 and up the singular */
const plural = (n: number, forms: { one: string; two: string; few: string; many: string }) => {
  switch (rules.select(n)) {
    case 'one':
      return forms.one;
    case 'two':
      return forms.two;
    case 'few':
      return `${n} ${forms.few}`;
    default:
      return `${n} ${forms.many}`;
  }
};
const chapters = (n: number) => plural(n, { one: 'أصحاح واحد', two: 'أصحاحان', few: 'أصحاحات', many: 'أصحاحًا' });
const verses = (n: number) => plural(n, { one: 'آية واحدة', two: 'آيتان', few: 'آيات', many: 'آية' });
const passages = (n: number) => plural(n, { one: 'شاهد واحد', two: 'شاهدان', few: 'شواهد', many: 'شاهدًا' });

